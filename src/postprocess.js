// ============================================================================
// Постобработка кириллицы: исправление известного бага PaddleOCR —
// латинских «двойников» внутри русских слов (T→Т, M→М, H→Н, P→Р, C→С, X→Х,
// O→О, A→А, B→В, E→Е, K→К и строчные аналоги).
//
// Пример: «Нaпример» (латинская «a» на 2-й позиции) → «Например».
// Слова, состоящие ТОЛЬКО из латиницы («Hello», «http», «OK»), не трогаются.
// ============================================================================

// Визуально неразличимые (или почти неразличимые) пары латиница → кириллица.
// Если какая-то пара даёт ложные срабатывания на ваших документах — просто
// уберите её из карты.
const HOMOGLYPHS = {
  A: 'А',
  B: 'В',
  C: 'С',
  E: 'Е',
  H: 'Н',
  K: 'К',
  M: 'М',
  O: 'О',
  P: 'Р',
  T: 'Т',
  X: 'Х',
  a: 'а',
  b: 'в',
  c: 'с',
  e: 'е',
  h: 'н',
  k: 'к',
  m: 'м',
  o: 'о',
  p: 'р',
  t: 'т',
  x: 'х',
  y: 'у',
};

// Непрерывный «пробег букв»: слово целиком, включая смешанные алфавиты.
// Знаки, цифры и пробелы остаются разделителями и не заменяются.
const LETTER_RUN = /[A-Za-z\u0400-\u04FF]+/g;

// Кириллица в Unicode: U+0400–U+04FF (включает Ё/ё).
const HAS_CYRILLIC = /[\u0400-\u04FF]/;

const LOOKALIKE_LATIN = /[A-Za-z]/g;

/** Является ли слово русским (содержит хотя бы одну кириллическую букву). */
export function isRussianWord(word) {
  return HAS_CYRILLIC.test(word);
}

/**
 * Главная функция постобработки.
 *
 * Для каждого «пробега букв»: если в нём есть кириллица — считаем слово
 * русским и заменяем латинские символы-двойники на кириллические.
 * Чисто латинские слова не трогаем.
 *
 * Ограничение метода: склеенные без пробела фрагменты («иPhone», «кафеBar»)
 * уже являются артефактом распознавания; эвристика правит их на основании
 * большинства кириллических букв и может ошибиться. Раздельные латинские
 * слова (URL, бренды) защищены всегда.
 *
 * @param {string} text — сырой текст из OCR (переносы строк сохраняются).
 * @returns {string}
 */
export function fixCyrillicHomoglyphs(text) {
  if (!text) return text;
  return text.replace(LETTER_RUN, (word) => {
    if (!isRussianWord(word)) return word;
    return word.replace(LOOKALIKE_LATIN, (ch) => HOMOGLYPHS[ch] ?? ch);
  });
}
